-- Tipologiche territoriali Lazio e tipi di indirizzo.
CREATE TABLE regions (
    id BIGSERIAL PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    code VARCHAR(60) NOT NULL,
    name VARCHAR(80) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_regions_company_code UNIQUE(company_id, code)
);
CREATE UNIQUE INDEX uq_regions_company_name ON regions(company_id, lower(name));

CREATE TABLE provinces (
    id BIGSERIAL PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    code VARCHAR(60) NOT NULL,
    name VARCHAR(80) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_provinces_company_code UNIQUE(company_id, code)
);
CREATE UNIQUE INDEX uq_provinces_company_name ON provinces(company_id, lower(name));

CREATE TABLE cities (
    id BIGSERIAL PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    code VARCHAR(60) NOT NULL,
    name VARCHAR(120) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_cities_company_code UNIQUE(company_id, code)
);
CREATE UNIQUE INDEX uq_cities_company_name ON cities(company_id, lower(name));

CREATE TABLE street_types (
    id BIGSERIAL PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    code VARCHAR(60) NOT NULL,
    name VARCHAR(80) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_street_types_company_code UNIQUE(company_id, code)
);
CREATE UNIQUE INDEX uq_street_types_company_name ON street_types(company_id, lower(name));

